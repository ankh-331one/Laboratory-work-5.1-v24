/**
В данной задаче необходимо сначала найти номер элемента,
удовлетворяющего одному условию, затем номер элемента,
удовлетворяющего другому условию, и только затем искать между ними
максимальный или минимальный элемент. При поиске элементов,
удовлетворяющих условию, необходимо использовать досрочный выход из
цикла. Ввод осуществляется из файла, вывод – в файл.

24. Задан целочисленный одномерный массив A из n элементов. Найти номер
последнего максимального элемента среди элементов, значения которых
лежат в диапазоне [t1, t2] и расположенных после первого элемента с
чётным значением. Если нет чётных элементов, искать с начала массива.
*/
#include <stdio.h>
#include <locale.h>
#include <malloc.h>


int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("\n-------------------------------------------------------------------------------------------\n");
// Ввод данных
    int n;
    do{
        printf("\nВведите количество элементов массива n: ");
        scanf("%d", &n);
        if (n <= 0 || n >= 100){
            printf("\n===========================================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n===========================================================================================\n");
        }
    }while (n <= 0 || n >= 100);

    printf("\n-------------------------------------------------------------------------------------------\n");
// Ввод данных
    int *A, i;
    A = (int*)malloc(n * sizeof(int));
    printf("\nВведите элементы массива A: \n");
    for (i = 0; i < n; i++){
        printf("\nA[%d]: ", i);
        scanf("%d", &A[i]);
    }

    printf("\n-------------------------------------------------------------------------------------------\n");
// Ввод данных
    int t1;
    printf("\nВведите левую границу диапазона поиска t1: ");
    scanf("%d", &t1);

    printf("\n-------------------------------------------------------------------------------------------\n");
// Ввод данных
    int t2;
    do{
        printf("\nВведите правую границу диапазона поиска t2: ");
        scanf("%d", &t2);
        if (t2 < t1){
            printf("\n===========================================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n===========================================================================================\n");
        }
    }while (t2 < t1);

    printf("\n-------------------------------------------------------------------------------------------\n");

    printf("\nВведено количество элементов массива n: %d\n", n);
    printf("\nВведён массив A: [ %d", A[0]);
    for (i = 1; i < n; i++){
        printf("; %d", A[i]);
    }
    printf(" ]\n");
    printf("\nВведены границы диапазона поиска [t1;t2]: [%d;%d]\n", t1, t2);

    printf("\n-------------------------------------------------------------------------------------------\n");

 // --- Поиск первого чётного элемента (с досрочным выходом) ---
    int flag = 1;
    i = 0;
    while (i < n && flag){
        if (A[i] % 2 == 0){
            flag = 0;// досрочный выход из цикла
        }else i++;
    }
// Определение стартовой позиции поиска
    if (flag){
        printf("\nНет чётных элементов в массиве. Поиск с начала массива.\n");
        i = 0;
    }else if(i < (n-1)){
        printf("\nНайден первый чётный элемент: A[%d] = %d\n", i, A[i]);
        flag = 1;
    }else{// Если стартовая позиция за пределами массива
        printf("\n===========================================================================================\n\t\t");
        printf("Нет элементов после первого чётного — он последний в массиве");
        printf("\n===========================================================================================\n");
    }
// --- Поиск последнего максимального элемента в диапазоне [t1, t2] ---
    if(flag){
        printf("\n-------------------------------------------------------------------------------------------\n");
        int max_id = 0, max = t1;
        for(i += 1;i < n;i++){
            if ((A[i] >= t1) && (A[i] <= t2) && (A[i] >= max)){
                max_id = i;
                max = A[i];
                flag = 0;
            }
        }
// --- Вывод результата --
        printf("\n===========================================================================================\n\n\t\t");
        printf("Результат\n");
        if (flag)
            printf("\nНет элементов в диапазоне [%d, %d] в заданной области поиска", t1, t2);
        else{
            printf("\nНомер последний максимальный элемент в диапазоне [%d, %d] после первого чётного: %d\nA[%d] = %d", t1, t2, max_id, max_id, A[max_id]);
        }
        printf("\n\n===========================================================================================\n");

    }

    free(A);

    return 0;
}
